)
insert into public.culture_repertoire (
  organization_id, title, title_kk, title_ru, author_kk, author_ru,
  note_kk, note_ru, category, sort_order, is_active
)
select org.id, i.title, i.title_kk, i.title_ru, i.author_kk, i.author_ru,
       i.note_kk, i.note_ru, i.category, i.sort_order, true
from incoming i cross join org
where not exists (
  select 1 from public.culture_repertoire r where r.organization_id = org.id
);

