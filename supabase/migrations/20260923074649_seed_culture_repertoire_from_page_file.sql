-- =====================================================================
-- culture_repertoire — перенос произведений из кода страницы /repertoire
--
-- Метки переведены в коды категорий. Генератор сверил перед выпуском, что
-- казахская и русская метки каждой строки дают ОДИН И ТОТ ЖЕ код и что
-- незнакомых меток нет — иначе произведение молча уехало бы в «другое».
--
-- sort_order идёт с шагом десять; он же рисуется номером на карточке, поэтому
-- вставка между десятым и двадцатым не сдвигает нумерацию у остальных.
--
-- ИДЕМПОТЕНТНОСТЬ. Вставка целиком пропускается, если в учреждении уже есть
-- хоть одно произведение: повторный запуск не создаст дубликаты и не перезапишет
-- то, что администратор успел поправить руками.
--
-- Учреждение находится по slug, а не по жёстко вписанному id.
-- =====================================================================

begin;

