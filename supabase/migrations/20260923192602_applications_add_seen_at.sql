-- =====================================================================
-- applications: колонка seen_at — "видели ли уже эту заявку"
--
-- Проект Supabase: culture-portal-kz (ref: lmawtmoqaetlvidffwnp)
--
-- ЗАЧЕМ. Красная точка в меню админки сейчас считает status = 'new', а
-- status одновременно и "непрочитано", и рабочий статус заявки. Это
-- значит, что дот гаснет только когда кто-то нажмёт «Обработана», а не
-- когда заявку просто открыли и посмотрели.
--
-- seen_at — отдельная, независимая от status отметка. NULL значит "ещё
-- никто не открывал список заявок с момента, как она пришла". Открытие
-- страницы «Заявки» проставляет её сразу всем непросмотренным, а status
-- как был рабочим процессом (в работе/обработана/отклонена), так им и
-- остаётся.
--
-- ХАРАКТЕР ОПЕРАЦИИ. ALTER TABLE ADD COLUMN на существующей таблице.
-- Колонка nullable, ничего не удаляется и не меняет тип. ADD COLUMN IF
-- NOT EXISTS и UPDATE ... WHERE seen_at is null делают скрипт идемпотентным.
--
-- RLS и GRANT не меняются: applications_admin_update и GRANT UPDATE уже
-- покрывают таблицу целиком, отдельного разрешения на новую колонку
-- Postgres не требует.
-- =====================================================================

begin;

alter table public.applications add column if not exists seen_at timestamptz;

comment on column public.applications.seen_at is
  'Когда сотрудник в последний раз открывал список заявок и видел эту запись. Независимо от status. NULL — ещё не видели, на этом держится красная точка в меню.';

-- Заявки, по которым статус уже сдвинулся с 'new', кто-то однозначно
-- открывал — иначе статус не сдвинулся бы. Проставляем seen_at задним
-- числом, чтобы после выката давно обработанные заявки не зажгли точку.
update public.applications
set seen_at = coalesce(processed_at, created_at)
where status <> 'new' and seen_at is null;

commit;

