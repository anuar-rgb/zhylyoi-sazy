-- =====================================================================
-- culture_staff — перенос людей, живших в коде страницы /staff
--
-- Страница переключена на таблицу. Без этого переноса она опустела бы:
-- в коде был один человек, и он должен остаться на месте.
--
-- Фотографии нет и в исходнике не было — карточка показывает инициалы.
--
-- ИДЕМПОТЕНТНОСТЬ. Вставка идёт только при отсутствии сотрудника с тем же
-- именем в том же учреждении. Повторный запуск не создаст дубликат и не
-- перезапишет то, что администратор успел поправить руками.
--
-- Учреждение находится по slug, а не по жёстко вписанному id: id генерируется
-- при создании и в разных средах разный.
-- =====================================================================

begin;

insert into public.culture_staff (
  organization_id, name, name_kk, name_ru, role_kk, role_ru, sort_order, is_active
)
select
  o.id,
  'Темирханов Алибек Жумаханович',
  'Темирханов Алибек Жумаханович',
  'Темирханов Алибек Жумаханович',
  'Басшысы',
  'Директор',
  -- Ноль, а не десять: руководитель стоит первым, а шаг в десять оставлен
  -- между остальными, чтобы вставить человека в середину без переписывания.
  0,
  true
from public.organizations o
where o.slug = 'ken-zhylyoi'
  and not exists (
    select 1 from public.culture_staff s
    where s.organization_id = o.id
      and s.name = 'Темирханов Алибек Жумаханович'
  );

commit;
