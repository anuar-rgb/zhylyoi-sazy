-- =====================================================================
-- Инициализация: первый регион и первое учреждение культуры
--
-- Проект Supabase: culture-portal-kz (ref: lmawtmoqaetlvidffwnp)
--
-- Свойства скрипта:
--   * идемпотентен через ON CONFLICT ... DO NOTHING;
--   * повторный запуск НИЧЕГО не перезаписывает — ни name, ни address,
--     ни type, ни is_active, ни любое другое поле. Если строка уже есть,
--     она остаётся ровно такой, какой её оставила админ-панель;
--   * опирается на UNIQUE-ограничения regions.code и organizations.slug;
--   * НЕ создаёт: пользователей Auth, профилей, мероприятий, новостей,
--     кружков, заявок, тестовых данных;
--   * НЕ содержит телефонов, email и персональных данных.
--
-- phone, email, description, logo_url не заполняются: реальные значения
-- не предоставлены. Проставляются позже обычным UPDATE по slug.
-- =====================================================================

begin;

-- ---------------------------------------------------------------------
-- 1. Регион
-- ---------------------------------------------------------------------
insert into public.regions (name, code, is_active)
values ('Атырау облысы', 'ATY', true)
on conflict (code) do nothing;

-- ---------------------------------------------------------------------
-- 2. Страховка: без региона организацию не создаём.
--    Без этой проверки INSERT ... SELECT ниже молча не вставил бы
--    ни одной строки, если бы регион отсутствовал.
-- ---------------------------------------------------------------------
do $guard$
begin
  if not exists (select 1 from public.regions where code = 'ATY') then
    raise exception 'Регион с code = ATY не найден — организация не создана.';
  end if;
end
$guard$;

-- ---------------------------------------------------------------------
-- 3. Первое учреждение культуры
--    region_id берётся по коду региона, а не хардкодом UUID.
-- ---------------------------------------------------------------------
insert into public.organizations (name, slug, type, region_id, address, is_active)
select 'Кең Жылыой мәдениет үйі',
       'ken-zhylyoi',
       'culture_house',
       r.id,
       'Махамбет даңғылы, 37, Құлсары қаласы',
       true
from public.regions r
where r.code = 'ATY'
on conflict (slug) do nothing;

commit;

