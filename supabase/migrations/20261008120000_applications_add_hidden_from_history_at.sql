-- «Скрыть из истории» для заявок в кружки.
--
-- Лента «История заявок» в админке очищается отдельно от самих заявок: скрытая заявка
-- пропадает только из ленты, а сводка по кружкам и список внутри кружка её по-прежнему
-- показывают. Совсем удаляется заявка только со страницы кружка.
--
-- Отметка в базе, а не в браузере: скрытое пропадает у всех сотрудников и на всех
-- устройствах. NULL — заявка видна в истории.
--
-- RLS и GRANT не меняются: applications_admin_update и GRANT UPDATE уже разрешают
-- сотрудникам обновлять строки своего учреждения (так же работает seen_at).
--
-- Применяется вручную в Supabase SQL Editor. Повторный запуск безопасен.
alter table public.applications add column if not exists hidden_from_history_at timestamptz;
