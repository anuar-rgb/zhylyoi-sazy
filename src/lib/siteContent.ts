/**
 * The editable text of the site.
 *
 * Which texts exist is decided by the page layout, which lives in code, so the keys
 * and their defaults are declared here. The database stores only what an institution
 * changed. Three things follow: no migration has to seed forty rows, the site reads
 * exactly as before until somebody edits something, and a new institution starts
 * from sensible wording instead of blank space.
 *
 * The defaults are neutral: they fit any house of culture, so a new institution's
 * site reads sensibly before anyone writes a word. Where the right text is the
 * institution's own name (the first screen's title, the «О нас» heading), the
 * default is empty and the page puts the name from the card (Настройки). «Кең
 * Жылыой»'s own wording is saved as its own texts in org_content.
 *
 * Texts of the optional pages (Об ансамбле, План, Народные коллективы) are mostly
 * empty: those pages are off for a new institution until it switches them on and
 * writes them.
 *
 * No server imports: the admin form renders straight from these groups.
 */
export type ContentField = {
  key: string;
  label: string;
  /** Rendered as a textarea in the admin form. */
  long?: boolean;
  /** The textarea's height in lines, for a long text such as the visiting rules. */
  rows?: number;
  kk: string;
  ru: string;
};

export type ContentGroup = {
  id: string;
  title: string;
  hint?: string;
  fields: ContentField[];
};

